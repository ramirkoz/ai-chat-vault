// Ukrainian for a Ukrainian browser, English for every other language.
const table = /^uk/i.test(globalThis.navigator?.language || '') ? uk : en;

export function t(key, values = {}) {
  return String(table[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

// Labels for text sent from web pages (site-tools buildSiteText).
export function siteLabels() {
  return {
    title: t('lblTitle'), source: t('lblSource'), selection: t('lblSelection'), language: t('lblLanguage'),
    automatic: t('lblAutomatic'), transcript: t('lblTranscript'), pageContent: t('lblPageContent'), shortened: t('lblShortened')
  };
}

export const uiLanguage = () => String(globalThis.navigator?.language || 'en').slice(0, 2).toLowerCase();
